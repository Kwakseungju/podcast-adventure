def _render_week(week_str: str, episodes: list[dict]) -> str:
    date_range = _week_date_range(week_str)
    cards_html = "\n".join(_render_card(ep) for ep in episodes)
    count = len(episodes)
    return f"""
<section class="week-section" data-week="{week_str}">
  <div class="week-header">
    <span class="week-label">{week_str}</span>
    <span class="week-date-range">{date_range}</span>
    <span class="week-count">{count} episode{'s' if count != 1 else ''}</span>
  </div>
  <div class="episode-grid">
{cards_html}
  </div>
</section>"""


