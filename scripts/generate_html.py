# Public entry point
# ---------------------------------------------------------------------------

def generate_html(output_path: Path, episodes: list[dict]) -> None:
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Group by week, newest first
    episodes_sorted = sorted(episodes, key=lambda e: e.get("published", ""), reverse=True)
    weeks_html = ""
    total_weeks = 0

    for week, group in groupby(episodes_sorted, key=lambda e: e.get("week", "Unknown")):
        eps_in_week = list(group)
        weeks_html += _render_week(week, eps_in_week)
        total_weeks += 1

    empty_msg = ""
    if not episodes:
        empty_msg = """
<div class="empty-state">
  <h2>No episodes yet</h2>
  <p>Run the tracker script to fetch and summarize the latest episodes.</p>
</div>"""

    now = datetime.now(timezone.utc)
    updated = f"{now.strftime('%B')} {now.day}, {now.strftime('%Y at %H:%M UTC')}"
    html = _HTML.format(
        css=_CSS,
        js=_JS,
        updated=updated,
        total_episodes=len(episodes),
        total_weeks=total_weeks,
        weeks_html=weeks_html,
        empty_msg=empty_msg,
    )

    output_path.write_text(html, encoding="utf-8")
    print(f"  HTML report: {len(episodes)} episodes across {total_weeks} weeks → {output_path}")
